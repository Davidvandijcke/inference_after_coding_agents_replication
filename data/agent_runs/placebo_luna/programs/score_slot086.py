#!/usr/bin/env python3
"""Score the CO2-topic randomized subgroup estimate from a compatible CSV."""

import argparse
import json

import pandas as pd
import statsmodels.formula.api as smf


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="Input CSV path")
    parser.add_argument("--output", required=True, help="Output JSON path")
    args = parser.parse_args()

    data = pd.read_csv(args.data)
    subset = data.loc[data["wtp_topic"] == "co2"].dropna(
        subset=["effect_below_one_to_one", "treatment", "block"]
    )
    model = smf.ols(
        "effect_below_one_to_one ~ treatment + C(block)", data=subset
    ).fit(cov_type="HC2", use_t=True)

    result = {
        "estimate": float(model.params["treatment"]),
        "std_error": float(model.bse["treatment"]),
        "p_value": float(model.pvalues["treatment"]),
    }
    with open(args.output, "w", encoding="utf-8") as output_file:
        json.dump(result, output_file, indent=2)
        output_file.write("\n")


if __name__ == "__main__":
    main()
