#!/usr/bin/env python3
"""Score the treatment effect on zero WTP when a reduction is ineffective."""

import argparse
import json

import pandas as pd
import statsmodels.formula.api as smf


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True, help="CSV dataset path")
    parser.add_argument("--output", required=True, help="JSON output path")
    args = parser.parse_args()

    data = pd.read_csv(args.data)
    analysis = data.dropna(subset=["wtp_zero_if_ineffective", "treatment", "block"])
    fit = smf.ols(
        "wtp_zero_if_ineffective ~ treatment + C(block)", data=analysis
    ).fit(cov_type="HC2")

    result = {
        "estimate": float(fit.params["treatment"]),
        "std_error": float(fit.bse["treatment"]),
        "p_value": float(fit.pvalues["treatment"]),
    }
    with open(args.output, "w", encoding="utf-8") as output_file:
        json.dump(result, output_file, indent=2)
        output_file.write("\n")


if __name__ == "__main__":
    main()
