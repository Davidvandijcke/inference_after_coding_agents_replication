#!/usr/bin/env python3
"""Score the year-two presenteeism treatment effect among employees aged 50+."""
import argparse
import json

import pandas as pd
import statsmodels.formula.api as smf


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True, help="CSV dataset with the evaluation columns")
    parser.add_argument("--output", required=True, help="Path for the JSON result")
    args = parser.parse_args()

    data = pd.read_csv(args.data)
    sample = data.loc[data["age_group"] == 3,
                      ["presenteeism_score_y2", "treatment", "block"]].dropna()
    model = smf.ols(
        "presenteeism_score_y2 ~ treatment + C(block)", data=sample
    ).fit(cov_type="HC2", use_t=True)
    result = {
        "estimate": float(model.params["treatment"]),
        "std_error": float(model.bse["treatment"]),
        "p_value": float(model.pvalues["treatment"]),
    }
    with open(args.output, "w", encoding="utf-8") as output:
        json.dump(result, output, indent=2)
        output.write("\n")


if __name__ == "__main__":
    main()
